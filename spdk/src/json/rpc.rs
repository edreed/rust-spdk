use core::slice;
use std::{
    ffi::CString,
    mem::transmute,
    ptr::{NonNull, null_mut},
};

use serde::{Deserialize, Serialize};
use spdk_sys::{
    spdk_json_val, spdk_json_val_len,
    spdk_json_val_type::{SPDK_JSON_VAL_OBJECT_BEGIN, SPDK_JSON_VAL_OBJECT_END},
    spdk_jsonrpc_begin_result, spdk_jsonrpc_end_result, spdk_jsonrpc_request,
    spdk_jsonrpc_send_error_response,
};

use crate::{
    errors::ErrorCode,
    json::{
        Deserializer, Serializer,
        serde::{Result, de::Value},
    },
    thread,
};

/// A Rust wrapper around an `spdk_jsonrpc_request` pointer.
#[repr(transparent)]
struct Request(NonNull<spdk_jsonrpc_request>);

impl Request {
    /// Creates a new instance for the specified `spdk_jsonrpc_request` pointer.
    unsafe fn new_unchecked(request: *mut spdk_jsonrpc_request) -> Self {
        unsafe { transmute(request) }
    }

    /// Sends the result value and completes the request.
    fn succeed<R: Serialize>(self, res: R) {
        let mut ser = Serializer::for_jsonrpc_request(&self);

        res.serialize(&mut ser).unwrap(); // TODO: Add error handling

        ser.finish(&self);
    }

    /// Sends an error response aand completes the request.
    fn fail<E: ErrorCode>(self, err: E) {
        let code = err.code();
        let msg = CString::new(err.to_string()).expect("valid C-string");

        unsafe {
            spdk_jsonrpc_send_error_response(self.0.as_ptr(), code, msg.as_ptr());
        }
    }
}

impl<'ser> Serializer<'ser, Request> {
    /// Creates a JSON [`Serializer`] used to serialize the response of the specified [`Request`].
    fn for_jsonrpc_request(request: &'ser Request) -> Self {
        unsafe { transmute(spdk_jsonrpc_begin_result(request.0.as_ptr())) }
    }

    /// Finishes serialization of the response and sends it to the requestor.
    fn finish(self, request: &'ser Request) {
        unsafe {
            spdk_jsonrpc_end_result(request.0.as_ptr(), self.0.as_ptr());
        }
    }
}

/// An error type for RPC calls that cannot fail.
///
/// Like [`std::convert::Infallible`], this enum cannot be created. It is used by the [`jsonrpc`]
/// attribute when generating the [`RpcCall`] implementation for an RPC function that does not
/// return a [`std::result::Result`] and therefore cannot fail.
///
/// [`jsonrpc`]: crate::jsonrpc
#[derive(Debug)]
pub enum Infallible {}

/// An internal trait for completing a JSON-RPC [`Request`] with the result of calling the RPC
/// function.
trait Response {
    /// Completes the JSON-RPC [`Request`] with itself as the result.
    fn complete(self, req: Request);
}

impl<T> Response for std::result::Result<T, Infallible>
where
    T: Serialize,
{
    fn complete(self, req: Request) {
        req.succeed(self.unwrap())
    }
}

impl<T, E> Response for std::result::Result<T, E>
where
    T: Serialize,
    E: ErrorCode,
{
    fn complete(self, req: Request) {
        match self {
            Ok(ret) => req.succeed(ret),
            Err(err) => req.fail(err),
        }
    }
}

/// The SPDK's JSON-RPC server invokes our callback with a null pointer for an RPC call that takes
/// no parameters. To enable the [`Deserializer`] to deserialize the [`RpcCall`] struct for an empty
/// parameter set, this empty object representation is used instead.
const NO_PARAMS: [spdk_json_val; 2] = [
    spdk_json_val {
        start: null_mut(),
        len: 0,
        type_: SPDK_JSON_VAL_OBJECT_BEGIN,
    },
    spdk_json_val {
        start: null_mut(),
        len: 0,
        type_: SPDK_JSON_VAL_OBJECT_END,
    },
];

/// This trait is used by the [`jsonrpc`] attribute to deserialize the RPC call's parameters and
/// invoke its implementation through the [`rpc_call`] function.
///
/// [`jsonrpc`]: crate::jsonrpc
#[allow(private_bounds)]
pub trait RpcCall<'call>: Deserialize<'call> {
    /// The result of the RPC [`invoke`] method.
    ///
    /// [`invoke`]: Self::invoke
    type Output: Response;

    /// Invokes the RPC call.
    fn invoke(self) -> impl Future<Output = Self::Output>;

    /// Creates an instance of the implementation of this trait
    ///
    /// # Safety
    ///
    /// The caller must ensure that the `params` pointer is either null, or non-null and points to a
    /// valid, well-formed array of `spdk_json_val` structures typically generated by a call to the
    /// `spdk_json_parse` function.
    unsafe fn from_params(mut params: *const spdk_json_val) -> Result<Self> {
        if params.is_null() {
            params = NO_PARAMS.as_ptr()
        }

        let params: &[Value<'call>] =
            unsafe { transmute(slice::from_raw_parts(params, spdk_json_val_len(params))) };
        let mut deserializer = Deserializer::new(params);

        Self::deserialize(&mut deserializer)
    }
}

/// A callback registered with the JSON-RPC subsystem that deserializes the parameters and invokes
/// the RPC call implementation.
///
/// # Safety
///
/// This function is intended to be used by the [`jsonrpc`] attribute as the callback for a JSON-RPC
/// callable function. It is passed to the `spdk_rpc_register_method` function. When called by the
/// JSON-RPC server, the parameters are guaranteed well-formed and valid for the duration of the
/// request (i.e. until `spdk_jsonrpc_end_result` is called).
///
/// [`jsonrpc`]: crate::jsonrpc
pub unsafe extern "C" fn rpc_call<'call, T>(
    request: *mut spdk_jsonrpc_request,
    params: *const spdk_json_val,
) where
    T: RpcCall<'call>,
{
    let fut = async move {
        // SAFETY: The `spdk_jsonrpc_request` is guaranteed to be non-null and valid until the
        // request is complete.
        let req = unsafe { Request::new_unchecked(request) };

        // SAFETY: The `spdk_json_val` is guaranteed to be non-null, well-formed and valid until the
        // request is complete.
        match unsafe { T::from_params(params) } {
            Ok(call) => {
                let res = call.invoke().await;

                res.complete(req);
            }
            Err(err) => {
                req.fail(err);
            }
        };
    };

    unsafe {
        thread::spawn_local_detached(fut);
    };
}
